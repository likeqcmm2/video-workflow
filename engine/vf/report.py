"""Numbers for the final report + the asset half of sources.md.

  vf stats     -> out/stats.json (+ short print): duration, narration length, voice, footage/graphics ratio,
                  shots, Wikimedia request statistics (from assets/commons/logs/requests.jsonl)
  vf sources   -> sources_assets.md (every asset actually on screen, with licence + scenes + flags);
                  sources.md = sources_assets.md + sources_facts.md (fact table written by the agent)
"""
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

from . import config

OUT = Path("out")


def wm_stats():
    log = Path("assets/commons/logs/requests.jsonl")
    if not log.exists():
        return None
    L = [json.loads(x) for x in log.read_text().splitlines() if x.strip()]
    req = [x for x in L if x["type"] != "retry"]
    sent = [x for x in req if x.get("cache") != "hit"]
    api_t = {"info", "search", "login", "metadata", "category", "api"}
    return {
        "sent": len(sent),
        "api": sum(x["type"] in api_t for x in sent),
        "file": sum(x["type"] in ("file", "thumbnail") for x in sent),
        "files_ok": sum(x["type"] in ("file", "thumbnail") and x.get("status") == 200 for x in sent),
        "http_429": sum(x.get("status") == 429 for x in req),
        "http_403": sum(x.get("status") == 403 for x in req),
        "http_5xx": sum((x.get("status") or 0) >= 500 for x in req),
        "retries": sum(x["type"] == "retry" for x in L),
        "cache_hits": sum(x.get("cache") == "hit" for x in req),
        "logged_in_requests": sum(bool(x.get("logged_in")) for x in sent),
        "first": L[0]["ts"] if L else None, "last": L[-1]["ts"] if L else None,
    }


def stats():
    from .qa import ratio
    from .scriptfmt import counts
    tl = json.loads((OUT / "timeline.json").read_text())
    c = counts()
    vo = [json.loads(p.read_text()) for p in sorted((OUT / "vo").glob("*.json"))]
    rt, total = ratio(tl)
    shots = [e for e in tl["timeline"] if e["type"] == "shot"]
    srcs = Counter(e["src"].split(":")[0] if ":" in e["src"] else "asset" for e in shots)
    wm = wm_stats()
    commons_used = sorted({e["src"] for e in shots if e["src"].startswith("cm:")})
    s = {"duration_s": round(tl["total"], 1), "duration": f"{int(tl['total'] // 60)}:{tl['total'] % 60:04.1f}",
         "narration": {k: c[k] for k in ("hook", "body", "total", "unit")},
         "voice_s": round(sum(v["dur"] for v in vo), 1),
         "voice_mean_sim": round(sum(v["sim"] for v in vo) / max(1, len(vo)), 3),
         "voice_min_sim": min((v["sim"] for v in vo), default=0),
         "ratio_pct": rt, "real_pct": round(rt.get("image", 0) + rt.get("video", 0), 1),
         "shots": len(shots), "scenes": c["scenes"], "shots_by_source": dict(srcs),
         "commons_files_on_screen": len(commons_used), "wikimedia": wm}
    (OUT / "stats.json").write_text(json.dumps(s, ensure_ascii=False, indent=1))
    print(json.dumps({k: v for k, v in s.items() if k != "wikimedia"}, ensure_ascii=False))
    if wm:
        print("wikimedia:", json.dumps(wm))
    return s


def sources():
    from .assets import commons_meta
    cfg = config.load()
    tl = json.loads((OUT / "timeline.json").read_text())
    shots = [e for e in tl["timeline"] if e["type"] == "shot" and e["kind"] != "gfx"]
    by = defaultdict(set)
    for e in shots:
        by[e["src"]].add(e["scene"])
    L = ["# Sources — assets on screen\n",
         "Generated by `vf sources` from the final timeline. Every asset carries a small on-screen credit for its "
         "whole duration. **CẦN KIỂM TRA QUYỀN** = needs a rights check before publishing.\n"]
    reg = {k: v for k, v in cfg["assets"].items() if k in by}
    if reg:
        L += ["## Registered footage\n", "| ID | File | Link | Licence | Scenes | Note |", "|---|---|---|---|---|---|"]
        for k, v in reg.items():
            flag = " **CẦN KIỂM TRA QUYỀN**" if v.get("rights_check") else ""
            L.append(f"| {k} | {v['path']} | {v.get('link', '')} | {v.get('license', '?')}{flag} | "
                     f"{', '.join(sorted(by[k]))} | {v.get('note', '')} |")
    nasa = sorted(k for k in by if k.startswith("nasa:"))
    if nasa:
        L += ["\n## NASA Image and Video Library (public domain; no NASA endorsement implied)\n",
              "| ID | Link | Scenes |", "|---|---|---|"]
        for k in nasa:
            L.append(f"| {k[5:]} | https://images.nasa.gov/details/{k[5:]} | {', '.join(sorted(by[k]))} |")
    cms = sorted(k for k in by if k.startswith("cm:"))
    if cms:
        L += ["\n## Wikimedia Commons\n", "| File | Author | Licence | Page | Scenes | Check |", "|---|---|---|---|---|---|"]
        for k in cms:
            m = commons_meta(k[3:]) or {}
            lic = m.get("license", "?")
            art = re.sub(r"\s+", " ", m.get("artist", "") or "")[:60]
            chk = "**CẦN KIỂM TRA QUYỀN**" if m.get("flag") or not m else (
                "attribution required (on screen)" if "BY" in lic.upper() else "")
            L.append(f"| {k[3:]} | {art} | {lic} | {m.get('page', '')} | {', '.join(sorted(by[k]))} | {chk} |")
    loc = sorted(k for k in by if k.startswith(("img:", "vid:")))
    if loc:
        L += ["\n## Other files\n", "| File | Credit shown | Scenes |", "|---|---|---|"]
        for k in loc:
            cr = next((e["credit"] for e in shots if e["src"] == k), "")
            L.append(f"| {k[4:]} | {cr} | {', '.join(sorted(by[k]))} |")
    mus = cfg["music"]
    files = {(v if isinstance(v, str) else v.get("file")) for v in mus["chapters"].values()} | ({mus["default"]} if mus.get("default") else set())
    if files:
        L += ["\n## Music\n"]
        for f in sorted(x for x in files if x):
            L.append(f"- {Path(f).stem.replace('_', ' ')} — {mus.get('credit', 'licence: see project.yaml music.credit')}")
    L += ["\n## Other\n", "- Fonts: Noto (SIL Open Font License).",
          "- Map data: Natural Earth (public domain)." if any(e["path"] == "map" for e in tl["timeline"] if e["type"] == "shot") else "",
          "- Code-built graphics and reconstructions are labelled on screen as reconstructions where they imitate documents."]
    Path("sources_assets.md").write_text("\n".join(x for x in L if x is not None) + "\n")
    facts = Path("sources_facts.md")
    Path("sources.md").write_text(Path("sources_assets.md").read_text() + ("\n" + facts.read_text() if facts.exists() else ""))
    # attribution lines for the video description (CC BY / BY-SA need them; PD/NASA are courtesy)
    cred = []
    for k, v in reg.items():
        if "BY" in str(v.get("license", "")).upper():
            cred.append(f"{k}: {v.get('credit', '')} — {v.get('license')} — {v.get('link', '')}")
    for k in cms:
        m = commons_meta(k[3:]) or {}
        if "BY" in m.get("license", "").upper():
            art = re.sub(r"\s+", " ", m.get("artist", "") or "")[:60]
            cred.append(f"{k[3:]} — {art} — {m.get('license')} — {m.get('page', '')}")
    if nasa:
        cred.append("Photos: NASA Image and Video Library (public domain; no endorsement implied)")
    if files:
        cred.append("Music: " + mus.get("credit", ""))
    OUT.mkdir(exist_ok=True)
    (OUT / "credits_for_description.txt").write_text("\n".join(cred) + "\n")
    print(f"sources_assets.md: {len(by)} assets; sources.md {'includes' if facts.exists() else 'WITHOUT'} sources_facts.md; "
          f"out/credits_for_description.txt {len(cred)} lines")
